"""Generate site/src/lib/sports-registry.generated.ts from config/sports.json (the one source for the sport registry).

    python -m scripts.gen_sports_registry          # write the file
    python -m scripts.gen_sports_registry --check  # exit 1 if the file is out of date
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "config" / "sports.json"
TARGET = ROOT / "site" / "src" / "lib" / "sports-registry.generated.ts"


def render() -> str:
    doc = json.loads(SOURCE.read_text(encoding="utf-8"))
    sports = json.dumps(doc["sports"], indent=2, ensure_ascii=False)
    return f"""// GENERATED by scripts/gen_sports_registry.py from config/sports.json. Do not edit.
export type SportResultType = {" | ".join(json.dumps(t) for t in doc["resultTypes"])};
export type SportLevel = {" | ".join(json.dumps(t) for t in doc["levels"])};
export type SportGender = {" | ".join(json.dumps(t) for t in doc["genders"])};
export interface SportDef {{ id: string; us: string; uk: string; icon: string; result_type: SportResultType; typical_duration_hours?: number }}

export const SPORT_LEVELS: readonly SportLevel[] = {json.dumps(doc["levels"])};
export const SPORT_GENDERS: readonly SportGender[] = {json.dumps(doc["genders"])};
export const NO_REDISTRIBUTION: readonly string[] = {json.dumps(doc.get("noRedistribution", []))};
export const DEFAULT_DURATION_HOURS = {json.dumps(doc["defaultDurationHours"])};
export const SPORTS: readonly SportDef[] = {sports};

const BY_ID = new Map(SPORTS.map((s) => [s.id, s]));

/** Unknown sport ids fail the build loudly. */
export function sportById(id: string): SportDef {{
  const found = BY_ID.get(id);
  if (!found) throw new Error(`unknown sport id "${{id}}"; known: ${{[...BY_ID.keys()].join(", ")}}`);
  return found;
}}

/** How long a game of this sport counts as "upcoming" after it starts (the table has no end time). */
export function sportDurationHours(id: string): number {{
  return sportById(id).typical_duration_hours ?? DEFAULT_DURATION_HOURS;
}}

/** False for a sport_events source whose terms forbid passing the raw data on. Any ICS/JSON/RSS/feed built from sport_events must filter on this. */
export function isRedistributable(source: string): boolean {{
  return !NO_REDISTRIBUTION.includes(source);
}}

export function sportLabel(id: string, country: string): string {{
  const s = sportById(id);
  return country === "gb" ? s.uk : s.us;
}}
"""


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
        if current != text:
            print(f"{TARGET.relative_to(ROOT)} is out of date: run python -m scripts.gen_sports_registry")
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
